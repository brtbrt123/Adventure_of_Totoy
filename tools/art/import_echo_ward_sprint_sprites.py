"""Import the Echo Step, Stone Ward and Sprint art (v1, approved by the human) into in-game sprite sources (art/src/*.txt).

Reference: art/reference/aspects_echo_ward_sprint/ (README.md, *_v1.png/.json, contact sheets, GIFs), drawn by
tools/art/make_aspect_echo_ward_sprint_art.py. This script runs that script's build() (no review files are written) and
writes every frame under its in-game name, with the anchor from the review JSON.

Writes (deterministic: fixed seeds, sorted iteration; running twice gives identical files):
  art/src/fx_echo_{place 5, anchor 6, countdown 4, vanish 5, trail_h 4, trail_d 4, trail_v 4, trail_head 4, arrive 5,
           bubble 4, dust 5}_N.txt and fx_echo_shield_<hero frame>_<1..4>.txt
  art/src/<set>_ward_{raise 4, hold 4, drop 3}_right_N.txt   set = hero2 | totoy_dagger | totoy_scythe (hero frames)
  art/src/fx_ward_{slab_raise 4, slab_hold 4, slab_drop 3, barrier 6, absorb 4, store_1/2/3 4 each, block 5,
           shockwave 8, cracks 4}_N.txt
  art/src/fx_sprint_{start 5, lines 4, wind 4, dust 6, end 4}_N.txt, fx_sprint_aura_<hero frame>_<1..6>.txt,
           fx_sprint_after_<hero frame>_<1..3>.txt
  art/src/ui_aspect_{echo_step,stone_ward,sprint}_1.txt and ui_aspect_<key>_lit_1..4.txt
  art/build/echo_ward_sprint_sprites_manifest.json   group -> frames, sizes, anchors (+ meaning, ms, extras)

OVERLAY NAMING: for a hero frame named F (hero2_*, totoy_dagger_*, totoy_scythe_*: idle_right_1-4, walk_right_1-6,
dash_right_1-4) the overlays are fx_echo_shield_F_<p 1..4>, fx_sprint_aura_F_<p 1..6> and fx_sprint_after_F_<k 1..3>.
They are cropped; their anchor is the hero frame's feet point in the crop, so presentation draws them like the hero
frame (same position, same mirroring by anchor). Missing name: draw nothing (Echo Step: use fx_echo_bubble instead).

WARD HERO FRAMES: <set>_ward_<phase>_right_N is the idle frame (raise/hold: idle N, drop: idle N) with the stone slab
composed in front. Each frame's anchor equals the anchor of the idle frame it is built from (the composite is shifted
by whole transparent columns/rows on its canvas, which keeps every size), so the feet line up with the idle frames.

Stale sources: files in art/src whose names start with the prefixes above AND whose header says they were generated by
this script are deleted when they are no longer produced (only this script's own output is ever removed).

Run from the project root, then validate, build and preview:
  python tools/art/import_echo_ward_sprint_sprites.py
  python tools/art/validate_art.py; python tools/art/build_art.py; python tools/art/preview_art.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import artlib  # noqa: E402
import make_aspect_echo_ward_sprint_art as G  # noqa: E402  (the v1 drawing; no side effects on import)

SRC = artlib.SRC_DIR
BUILD = artlib.BUILD_DIR
PAL = artlib.load_palette()
T = "."
GENERATOR = "tools/art/import_echo_ward_sprint_sprites.py"
HERO_SETS = tuple(G.HERO_SETS.values())
PREFIXES = ("fx_echo_", "fx_ward_", "fx_sprint_", "ui_aspect_echo_step_", "ui_aspect_stone_ward_", "ui_aspect_sprint_") + tuple(
    f"{vid}_ward_" for vid in HERO_SETS)

ANCHOR_MEANING = {
    "fx_echo_place": "Totoy's feet where he places the echo (24,42); over the hero",
    "fx_echo_anchor": "the echo's feet (24,42), a fixed world point; sort by its ground y like a character",
    "fx_echo_countdown": "the echo's feet (24,42); replaces fx_echo_anchor for the last ~320 ms",
    "fx_echo_vanish": "Totoy's feet where the recall fires (24,42); the hero is not drawn",
    "fx_echo_trail_h": "start of the line (0,4); repeat every 16 px along +x at chest height (feet - 14)",
    "fx_echo_trail_d": "top-left (0,0); repeat every (16,16) down-right at chest height (feet - 14)",
    "fx_echo_trail_v": "top centre (4,0); repeat every 16 px along +y",
    "fx_echo_trail_head": "comet head centre (8,8) at the echo end, chest height (feet - 14)",
    "fx_echo_arrive": "the echo's feet (24,42); hero drawn at the echo from frame 2",
    "fx_echo_bubble": "Totoy's feet (20,44); generic i-frame bubble over any hero frame",
    "fx_echo_shield": "the hero frame's feet point inside the crop; draw on top of that hero frame, mirrored with him",
    "fx_echo_dust": "feet (16,12)",
    "hero2_ward": "feet, identical to the idle frame it is built from (hero frame)",
    "totoy_dagger_ward": "feet, identical to the idle frame it is built from (hero frame)",
    "totoy_scythe_ward": "feet, identical to the idle frame it is built from (hero frame)",
    "fx_ward_slab": "Totoy's feet (12,35); the slab alone, over any hero frame",
    "fx_ward_barrier": "Totoy's feet (16,44); over the hero and slab",
    "fx_ward_absorb": "Totoy's feet (16,44); replaces the barrier when a hit is absorbed",
    "fx_ward_store": "Totoy's feet (16,44); over the barrier, level = hits stored (3 = 3+ or max)",
    "fx_ward_block": "the hit point (16,16), about feet + (22,-16) on the ward front",
    "fx_ward_shockwave": "Totoy's feet (72,50); ring radius per frame in radius_px (ry = 0.45 rx)",
    "fx_ward_cracks": "Totoy's feet (48,24); floor decal, draw under every character",
    "fx_sprint_start": "feet (24,35)",
    "fx_sprint_lines": "feet (36,35); the lines trail behind a right-facing hero",
    "fx_sprint_wind": "feet (14,35); over the hero",
    "fx_sprint_dust": "feet (28,12)",
    "fx_sprint_aura": "the hero frame's feet point inside the crop; draw on top of that hero frame, mirrored with him",
    "fx_sprint_after": "the hero frame's feet point inside the crop; draw BEHIND the hero at an earlier position (or behind_px against his facing), mirrored with him",
    "fx_sprint_end": "feet (24,35)",
    "ui_aspect": "icon centre (12,12)",
}


def meaning(base: str) -> str:
    for key in sorted(ANCHOR_MEANING, key=len, reverse=True):
        if base.startswith(key):
            return ANCHOR_MEANING[key]
    return ""


def check(name: str, g: list, anchor: tuple[int, int]) -> None:
    h, w = len(g), len(g[0])
    if w % 8 or h % 8 or max(w, h) > artlib.SPRITE_MAX:
        raise SystemExit(f"{name}: size {w}x{h} is not a multiple of 8 (max {artlib.SPRITE_MAX})")
    if any(len(r) != w for r in g):
        raise SystemExit(f"{name}: ragged rows")
    if not (0 <= anchor[0] <= w and 0 <= anchor[1] <= h):
        raise SystemExit(f"{name}: anchor {anchor} outside {w}x{h}")
    used = {c for row in g for c in row}
    bad = used & set(PAL.reserved) | (used - set(PAL.by_symbol) - {T})
    if bad:
        raise SystemExit(f"{name}: uses reserved or unknown symbols {sorted(bad)}")
    if used <= {T}:
        raise SystemExit(f"{name}: empty")


def shift(g: list, dx: int, dy: int) -> list:
    """Move the picture by (dx, dy) on its own canvas; only fully transparent rows/columns may fall off."""
    h, w = len(g), len(g[0])
    out = [[T] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            c = g[y][x]
            if c == T:
                continue
            nx, ny = x + dx, y + dy
            if not (0 <= nx < w and 0 <= ny < h):
                raise ValueError("opaque pixel would leave the canvas")
            out[ny][nx] = c
    return out


def ward_hero_entries(entries: list) -> list:
    """Give each <set>_ward_* frame the anchor of the idle frame it is built from (same picture in the world)."""
    idle = {f"{vid}_idle_right_{n}": G.load_sprite(f"{vid}_idle_right_{n}")[1] for vid in HERO_SETS for n in range(1, 5)}
    out = []
    for name, g, anchor, extra in entries:
        for vid in HERO_SETS:
            if name.startswith(f"{vid}_ward_"):
                k = int(name.rsplit("_", 1)[1])
                src = f"{vid}_idle_right_{(k - 1) % 4 + 1}"  # build(): idle[i % 4] for frame i + 1
                want = idle[src]
                dx, dy = want[0] - anchor[0], want[1] - anchor[1]
                try:
                    g = shift(g, dx, dy)
                    anchor = want
                except ValueError:
                    raise SystemExit(f"{name}: cannot move the anchor to {want} (the idle anchor of {src})")
                extra = {**extra, "idle_frame": src}
                break
        out.append((name, g, anchor, extra))
    return out


def note_for(name: str, extra: dict) -> str:
    if "hero_frame" in extra:
        kind = "Echo Step shield" if name.startswith("fx_echo_") else ("Sprint aura" if "_aura_" in name else "Sprint afterimage")
        return f"{kind} over {extra['hero_frame']}, {'ghost' if 'ghost' in extra else 'phase'} {extra.get('ghost', extra.get('phase'))}"
    if "idle_frame" in extra:
        return f"Stone Ward hero frame built from {extra['idle_frame']}"
    return name.rsplit("_", 1)[0].replace("_", " ")


def write_sprite(name: str, g: list, anchor: tuple[int, int], note: str) -> None:
    lines = ["# kind: sprite", f"# anchor: {anchor[0]},{anchor[1]}",
             f"# generated by {GENERATOR} from tools/art/make_aspect_echo_ward_sprint_art.py ({note}); do not hand-edit"]
    lines += ["".join(row) for row in g]
    (SRC / f"{name}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    a = G.build()
    entries = ward_hero_entries(G.echo_sprites(a) + G.ward_sprites(a) + G.sprint_sprites(a) + G.icon_sprites(a))
    names = [e[0] for e in entries]
    if len(set(names)) != len(names):
        raise SystemExit("duplicate sprite names")
    for name, g, anchor, _ in entries:
        check(name, g, anchor)
    existing = {p.stem for p in SRC.glob("*.txt")}
    for name in names:  # never overwrite a source this script did not write (for example a hand-made hero frame)
        path = SRC / f"{name}.txt"
        if name in existing and GENERATOR not in "".join(path.read_text(encoding="utf-8").splitlines()[:4]):
            raise SystemExit(f"{name}: art/src already has this name from another source; refusing to overwrite")

    keep = set(names)
    removed = 0
    for path in sorted(SRC.glob("*.txt")):
        if path.stem in keep or not path.stem.startswith(PREFIXES):
            continue
        if any(GENERATOR in line for line in path.read_text(encoding="utf-8").splitlines()[:4]):
            path.unlink()
            removed += 1

    manifest: dict[str, dict] = {}
    for name, g, anchor, extra in entries:
        write_sprite(name, g, anchor, note_for(name, extra))
        base, n = name.rsplit("_", 1)
        e = manifest.setdefault(base, {"frames": 0, "anchors": [], "frame_sizes": [], "ms": []})
        e["frames"] += 1
        assert int(n) == e["frames"], f"{name}: frames must be numbered 1..N in order"
        e["anchors"].append(list(anchor))
        e["frame_sizes"].append([len(g[0]), len(g)])
        if "ms" in extra:
            e["ms"].append(extra["ms"])
        for key in ("hero_frame", "level", "tile", "use"):
            if key in extra:
                e[key] = extra[key]
        for key in ("radius_px", "behind_px", "idle_frame"):
            if key in extra:
                e.setdefault(key, []).append(extra[key])
    for base, e in manifest.items():
        for key, single in (("anchors", "anchor"), ("frame_sizes", "size")):
            if all(v == e[key][0] for v in e[key]):
                e[single] = e[key][0]
        if not e["ms"]:
            del e["ms"]
        e["anchor_meaning"] = meaning(base)

    def count(pred) -> int:
        return sum(1 for n in names if pred(n))

    groups = {
        "fx_echo_shield": count(lambda n: n.startswith("fx_echo_shield_")),
        "fx_echo_other": count(lambda n: n.startswith("fx_echo_") and not n.startswith("fx_echo_shield_")),
        "hero_ward_frames": count(lambda n: any(n.startswith(f"{v}_ward_") for v in HERO_SETS)),
        "fx_ward": count(lambda n: n.startswith("fx_ward_")),
        "fx_sprint_aura": count(lambda n: n.startswith("fx_sprint_aura_")),
        "fx_sprint_after": count(lambda n: n.startswith("fx_sprint_after_")),
        "fx_sprint_other": count(lambda n: n.startswith("fx_sprint_") and not n.startswith(("fx_sprint_aura_", "fx_sprint_after_"))),
        "ui_aspect": count(lambda n: n.startswith("ui_aspect_")),
    }
    covered = [f"{s}_right_1..{c}" for s, c in G.MOVE_STATES]
    data = {
        "generator": GENERATOR,
        "art": "tools/art/make_aspect_echo_ward_sprint_art.py (v1, approved); reference and review files: art/reference/aspects_echo_ward_sprint/README.md",
        "note": "Sprite groups: name -> frame count (frames are <name>_1..N), sizes, anchors per frame and their meaning, suggested ms per frame. Anchors are the point that goes on the given world position; mirror around the anchor for a left-facing hero.",
        "naming": {
            "frames": "<group>_<n>, n from 1",
            "hero_ward_frames": "<set>_ward_<raise|hold|drop>_right_<n> (raise 4, hold 4 loop, drop 3), set = hero2 (katana) | totoy_dagger | totoy_scythe. Hero frames: the idle body with the slab; anchor = the matching idle frame's anchor (idle_frame lists it), left = right mirrored by the anchor.",
            "overlays": "fx_echo_shield_<F>_<p 1..4>, fx_sprint_aura_<F>_<p 1..6>, fx_sprint_after_<F>_<k 1..3>, where F is the hero frame being drawn (hero2_*, totoy_dagger_*, totoy_scythe_*: " + ", ".join(covered) + "). Cropped; draw by the overlay's own anchor at the hero's feet with the hero's mirroring. Phase timed from the aspect's start (shield 70 ms, aura 80 ms), independent of the hero frame. Afterimage k is drawn behind the hero where he was k x ~150 ms ago, or at behind_px against his facing. Missing name (attack, parry, hurt, victory, coil, lightning frames): draw none; for Echo Step use fx_echo_bubble.",
            "icons": "ui_aspect_<echo_step|stone_ward|sprint>_1 (24x24), ui_aspect_<key>_lit_1..4 optional HUD loop while active (~120 ms)",
        },
        "hero_sets": dict(G.HERO_SETS),
        "covered_hero_frames": covered,
        "shockwave_radius_px": list(G.SW_R),
        "shockwave_floor_squash": G.SW_SQ,
        "afterimage_step_px": G.AFTER_STEP,
        "counts": {**groups, "total": len(names)},
        "sprites": {k: manifest[k] for k in sorted(manifest)},
    }
    (BUILD / "echo_ward_sprint_sprites_manifest.json").write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(names)} sprite sources ({groups}), removed {removed} stale, and art/build/echo_ward_sprint_sprites_manifest.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
