"""Import the approved chapter 1 NPC and interactable sprites into in-game sprite sources (art/src/*.txt).

Source: art/reference/chapter1_characters_v2/npc_sprites_v2.png + npc_sprites_v2.json (made by
tools/art/make_chapter1_characters_v2.py; see that folder's README.md). Every frame of the atlas is written under its
own name with its anchor (feet):
  art/src/npc_<name>_<state>_right_<n>.txt   mira, tovan, edda (idle 4, walk 6, talk 3, one pose), elder, child, worker
                                             (idle 4, walk 6); 32x40, anchor 16,37; left = mirrored around the anchor
  art/src/obj_*.txt                          dummy, dummy_hit, chest_closed, chest_open, herbs, lantern, lantern_post
and art/build/chapter1_npc_sprites_manifest.json (the source JSON's states with frame counts and ticks).

Deterministic (same source = same files). Every pixel must be a Totoy 36 colour with hard alpha and never a reserved
combat colour (the source script guarantees it; this script checks again and stops otherwise). Stale sources this
script wrote earlier (npc_* / obj_* whose header names this script) are removed when no longer in the atlas; a file
with the same name from another source is never overwritten.

Run from the project root, then validate, build and preview:
  python tools/art/import_chapter1_npc_sprites.py
  python tools/art/validate_art.py; python tools/art/build_art.py; python tools/art/preview_art.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import artlib  # noqa: E402

REF = artlib.ROOT / "art" / "reference" / "chapter1_characters_v2"
SRC = artlib.SRC_DIR
BUILD = artlib.BUILD_DIR
GENERATOR = "tools/art/import_chapter1_npc_sprites.py"
PREFIXES = ("npc_", "obj_")


def main() -> int:
    data = json.loads((REF / "npc_sprites_v2.json").read_text(encoding="utf-8"))
    atlas = Image.open(REF / data["image"]).convert("RGBA")
    palette = json.loads(artlib.PALETTE_PATH.read_text(encoding="utf-8"))
    reserved = set(palette.get("reserved", []))
    by_rgb: dict[tuple[int, int, int], str] = {}
    for entry in palette["colors"]:
        h = entry["hex"].lstrip("#")
        by_rgb[(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))] = entry["symbol"]

    frames: dict = data["frames"]
    names = sorted(frames)
    existing = {p.stem for p in SRC.glob("*.txt")}
    for name in names:
        if not name.startswith(PREFIXES):
            raise SystemExit(f"{name}: unexpected frame name")
        path = SRC / f"{name}.txt"
        if name in existing and GENERATOR not in "".join(path.read_text(encoding="utf-8").splitlines()[:4]):
            raise SystemExit(f"{name}: art/src already has this name from another source; refusing to overwrite")

    removed = 0
    for path in sorted(SRC.glob("*.txt")):
        if path.stem in frames or not path.stem.startswith(PREFIXES):
            continue
        if any(GENERATOR in line for line in path.read_text(encoding="utf-8").splitlines()[:4]):
            path.unlink()
            removed += 1

    for name in names:
        f = frames[name]
        x, y, w, h = int(f["x"]), int(f["y"]), int(f["w"]), int(f["h"])
        if w % artlib.SPRITE_STEP or h % artlib.SPRITE_STEP:
            raise SystemExit(f"{name}: {w}x{h} is not a multiple of {artlib.SPRITE_STEP}")
        rows: list[str] = []
        for yy in range(y, y + h):
            row = []
            for xx in range(x, x + w):
                r, g, b, a = atlas.getpixel((xx, yy))
                if a == 0:
                    row.append(".")
                    continue
                if a != 255:
                    raise SystemExit(f"{name}: semi-transparent pixel at {xx - x},{yy - y}")
                symbol = by_rgb.get((r, g, b))
                if symbol is None or symbol in reserved:
                    raise SystemExit(f"{name}: colour {(r, g, b)} at {xx - x},{yy - y} is not an allowed palette colour")
                row.append(symbol)
            rows.append("".join(row))
        ax, ay = int(f.get("ax", w // 2)), int(f.get("ay", h - 1))
        lines = ["# kind: sprite", f"# anchor: {ax},{ay}",
                 f"# generated by {GENERATOR} from art/reference/chapter1_characters_v2/npc_sprites_v2.png; do not hand-edit"]
        (SRC / f"{name}.txt").write_text("\n".join(lines + rows) + "\n", encoding="utf-8", newline="\n")

    manifest = {
        "note": "Chapter 1 NPCs and interactables in the game atlas (art/build/sprites.json). Names: npc_<name>_<state>_right_<n> (left = mirror around the anchor), obj_*_<n>. Ticks per frame at 60 per second.",
        "source": "art/reference/chapter1_characters_v2/npc_sprites_v2.json",
        "states": data.get("states", {}),
        "objects": data.get("objects", {}),
        "frames": names,
    }
    (BUILD / "chapter1_npc_sprites_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(names)} sprite sources (removed {removed} stale), art/build/chapter1_npc_sprites_manifest.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
