    c = F.Canvas(48, 48, 24, 24)
    cx = cy = 24
    if i == 0:
        c.disc(cx, cy, 3.6, 3.6, "1")
        for d in range(4, 12):
            for x, y in ((cx + d, cy), (cx - d, cy), (cx, cy + d), (cx, cy - d)):
                c.put(x, y, "1" if d < 7 else "x")
        c.halo("x", 1.0, {"1"})
    elif i == 1:
        star(c, cx, cy, 16, 20, 13, GOLD_RAY, 0, True)
        c.disc(cx, cy, 5, 5, "1")
        c.halo("x", 1.0, {"1"})
        ring(c, cx, cy, 9, "x", 0.6)
    elif i == 2:
        star(c, cx, cy, 8, 22, 15, GOLD_RAY, 22.5, True)
        c.disc(cx, cy, 5.5, 5.5, "1")
        c.halo("x", 1.0, {"1"})
        ring(c, cx, cy, 13, "x")
        ring(c, cx, cy, 14, "y", 0.7)
    elif i == 3:
        ring(c, cx, cy, 17, "x")
        ring(c, cx, cy, 18, "y", 0.8)
        ring(c, cx, cy, 10, "1", 0.5)
        for k in range(8):
            spike(c, cx, cy, math.radians(k * 45), 18, 23, ["1", "x", "x", "y"])
