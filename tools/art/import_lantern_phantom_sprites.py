"""Import the Spirit Lantern and Phantom Cut art (v2) into in-game sprite sources (art/src/*.txt).

Reference: art/reference/aspects_lantern_phantom/ (README.md, *_v2.png/.json, contact sheets, GIFs), drawn by
tools/art/make_aspect_lantern_phantom_art.py. This script runs that script's build() (no review files are written) and
writes every frame under its in-game name, with the anchor from the review JSON.

Writes (deterministic: fixed seeds, sorted iteration; running twice gives identical files):
  art/src/fx_lantern_{place 4, idle 6, pulse 4, fade 6, pool_open 3, pool_idle 4, pool_pulse 5, motes 6, spark 6}_N.txt
  art/src/fx_phantom_glow_<hero frame>_<1..6>.txt   buff glow over one hero frame (see GLOW NAMING below)
  art/src/fx_phantom_start_1..5, fx_phantom_end_1..4, fx_phantom_spark_1..5, fx_phantom_marker_1..4
  art/src/fx_phantom_ghost_<weapon>_<swing>_<1..4>.txt, fx_phantom_arc_<weapon>_<swing>_<1..4>.txt
           weapon = katana (3 swings) | dagger (4) | scythe (3)
  art/src/ui_aspect_spirit_lantern_1, ui_aspect_phantom_cut_1, ui_aspect_spirit_lantern_lit_1..4
  art/build/lantern_phantom_sprites_manifest.json   group -> frames, sizes, anchors (+ meaning, ms, sources)

GLOW NAMING: for a hero frame named F (for example hero2_attack2_right_3, totoy_dagger_walk_right_5,
totoy_scythe_parry_right_1) the overlay for shimmer phase p (1..6) is "fx_phantom_glow_" + F + "_" + p. It is cropped to
the glow; its anchor is the hero frame's feet point in the crop, so presentation draws it exactly like the hero frame
(same position, same mirroring by anchor). Covered: idle 1-4, walk 1-6, dash 1-4, parry 1-6, hurt 1-4 and
attack<s>_right_1..6 of hero2 (s 1-3), totoy_dagger (s 1-4) and totoy_scythe (s 1-3). Not covered: victory, the
Reaper's Coil poses (totoy_scythe_coil_*) and the Lightning set (totoy_lightning_*): no overlay = draw none.

Stale sources: files in art/src whose names start with the prefixes above AND whose header says they were generated by
this script are deleted when they are no longer produced (only this script's own output is ever removed).

Run from the project root, then validate, build and preview:
  python tools/art/import_lantern_phantom_sprites.py
  python tools/art/validate_art.py; python tools/art/build_art.py; python tools/art/preview_art.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import artlib  # noqa: E402
import make_aspect_lantern_phantom_art as G  # noqa: E402  (the v2 drawing; no side effects on import)

SRC = artlib.SRC_DIR
BUILD = artlib.BUILD_DIR
PAL = artlib.load_palette()
T = "."
GENERATOR = "tools/art/import_lantern_phantom_sprites.py"
PREFIXES = ("fx_lantern_", "fx_phantom_", "ui_aspect_spirit_lantern_", "ui_aspect_phantom_cut_")

ANCHOR_MEANING = {
    "fx_lantern_place": "lantern's ground point (16,29)",
    "fx_lantern_idle": "lantern's ground point (16,29)",
    "fx_lantern_pulse": "lantern's ground point (16,29)",
    "fx_lantern_fade": "lantern's ground point (16,29)",
    "fx_lantern_pool": "lantern's ground point = pool centre (48,24); floor decal, draw under every character; ellipse rx 44 / ry 20",
    "fx_lantern_motes": "Totoy's feet (16,38); heal motes, draw over the hero on a pulse while he stands in the light",
    "fx_lantern_spark": "Totoy's chest / weapon hand (16,16), about feet + (2,-15); Edge sparks, start 1-2 frames after motes 1",
    "fx_phantom_glow": "the hero frame's feet point inside the crop; draw on top of that hero frame at the hero's feet, mirrored with him",
    "fx_phantom_start": "Totoy's feet (24,44); buff start burst, over the hero",
    "fx_phantom_end": "Totoy's feet (24,44); buff end fade, over the hero",
    "fx_phantom_ghost": "the phantom's feet = Totoy's feet + ghost_offset_px along his facing; same canvas/anchor as the source attack frame",
    "fx_phantom_arc_katana": "the phantom's feet (40,56); draw over the ghost",
    "fx_phantom_arc_dagger": "the phantom's feet (16,44); draw over the ghost",
    "fx_phantom_arc_scythe": "the phantom's feet (40,56); same canvas as fx_scythe_arc_*; draw over the ghost",
    "fx_phantom_spark": "where the echo hits (16,16); start on arc phase 2",
    "fx_phantom_marker": "bottom centre (8,15); 3 px above Totoy's head while the buff runs",
    "ui_aspect": "icon centre (12,12)",
}


def meaning(base: str) -> str:
    for key in sorted(ANCHOR_MEANING, key=len, reverse=True):
        if base.startswith(key):
            return ANCHOR_MEANING[key]
    return ""


def check(name: str, g: list, anchor: tuple[int, int]) -> None:
    h, w = len(g), len(g[0])
    if w % 8 or h % 8 or max(w, h) > artlib.SPRITE_MAX:
        raise SystemExit(f"{name}: size {w}x{h} is not a multiple of 8 (max {artlib.SPRITE_MAX})")
    if not (0 <= anchor[0] <= w and 0 <= anchor[1] <= h):
        raise SystemExit(f"{name}: anchor {anchor} outside {w}x{h}")
    bad = {c for row in g for c in row} & (set(PAL.reserved) | ({c for row in g for c in row} - set(PAL.by_symbol) - {T}))
    if bad:
        raise SystemExit(f"{name}: uses reserved or unknown symbols {sorted(bad)}")


def note_for(name: str, extra: dict) -> str:
    if "hero_frame" in extra:
        return f"Phantom Cut buff glow over {extra['hero_frame']}, phase {extra['phase']}"
    if "source" in extra:
        return f"Phantom Cut ghost from {extra['source']}, {extra['mode']}"
    if "swing" in extra:
        return f"Phantom Cut echo arc, swing {extra['swing']}, {extra['phase']}"
    return name.rsplit("_", 1)[0].replace("_", " ")


def write_sprite(name: str, g: list, anchor: tuple[int, int], note: str) -> str:
    lines = ["# kind: sprite", f"# anchor: {anchor[0]},{anchor[1]}",
             f"# generated by {GENERATOR} from tools/art/make_aspect_lantern_phantom_art.py ({note}); do not hand-edit"]
    lines += ["".join(row) for row in g]
    text = "\n".join(lines) + "\n"
    (SRC / f"{name}.txt").write_text(text, encoding="utf-8", newline="\n")
    return text


def main() -> int:
    a = G.build()
    entries = G.lantern_sprites(a) + G.phantom_sprites(a) + G.icon_sprites(a)
    names = [e[0] for e in entries]
    if len(set(names)) != len(names):
        raise SystemExit("duplicate sprite names")
    for name, g, anchor, _ in entries:
        check(name, g, anchor)

    keep = set(names)
    removed = 0
    for path in sorted(SRC.glob("*.txt")):
        if path.stem in keep or not path.stem.startswith(PREFIXES):
            continue
        head = path.read_text(encoding="utf-8").splitlines()[:4]
        if any(GENERATOR in line for line in head):
            path.unlink()
            removed += 1

    manifest: dict[str, dict] = {}
    for name, g, anchor, extra in entries:
        write_sprite(name, g, anchor, note_for(name, extra))
        base, n = name.rsplit("_", 1)
        e = manifest.setdefault(base, {"frames": 0, "anchors": [], "frame_sizes": [], "ms": []})
        e["frames"] += 1
        assert int(n) == e["frames"], f"{name}: frames must be numbered 1..N in order"
        e["anchors"].append(list(anchor))
        e["frame_sizes"].append([len(g[0]), len(g)])
        if "ms" in extra:
            e["ms"].append(extra["ms"])
        for key in ("hero_frame", "swing"):
            if key in extra:
                e[key] = extra[key]
        if "source" in extra:
            e.setdefault("sources", []).append(extra["source"])
        if "use" in extra:
            e["use"] = extra["use"]
    for base, e in manifest.items():
        for key, single in (("anchors", "anchor"), ("frame_sizes", "size")):
            if all(v == e[key][0] for v in e[key]):
                e[single] = e[key][0]
        if not e["ms"]:
            del e["ms"]
        e["anchor_meaning"] = meaning(base)
    groups = {
        "fx_lantern": sum(1 for n in names if n.startswith("fx_lantern_")),
        "fx_phantom_glow": sum(1 for n in names if n.startswith("fx_phantom_glow_")),
        "fx_phantom_other": sum(1 for n in names if n.startswith("fx_phantom_") and not n.startswith("fx_phantom_glow_")),
        "ui_aspect": sum(1 for n in names if n.startswith("ui_aspect_")),
    }
    data = {
        "generator": GENERATOR,
        "art": "tools/art/make_aspect_lantern_phantom_art.py (v2); reference and review files: art/reference/aspects_lantern_phantom/README.md",
        "note": "Sprite groups: name -> frame count (frames are <name>_1..N), sizes, anchors per frame and their meaning, suggested ms per frame. Anchors are the point that goes on the given world position; mirror around the anchor for a left-facing hero.",
        "glow_naming": "fx_phantom_glow_<hero frame name>_<phase 1..6>: the buff glow over that exact hero frame (hero2_*, totoy_dagger_*, totoy_scythe_*: idle, walk, dash, parry, hurt, attack<s> 1-6). Phase = (ticks since the buff started / about 5 ticks at 60 Hz) % 6 + 1 (about 80 ms), independent of the hero frame. Draw it on top of the hero frame with the same position and mirroring, by its own anchor (it is cropped). Missing name (victory, coil poses, lightning set): draw nothing.",
        "weapons": {w: {"hero_set": v[0], "swings": v[3]} for w, v in G.WEAPONS.items()},
        "ghost_offset_px": G.GHOST_OFFSET,
        "pool_radius_px": {"rx": G.PRX, "ry": G.PRY},
        "counts": {**groups, "total": len(names)},
        "sprites": {k: manifest[k] for k in sorted(manifest)},
    }
    (BUILD / "lantern_phantom_sprites_manifest.json").write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(names)} sprite sources ({groups}), removed {removed} stale, and art/build/lantern_phantom_sprites_manifest.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
